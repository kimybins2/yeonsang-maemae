const norm = (s) => String(s || "").replace(/\s/g, "").toLowerCase();
function hashStr(s){ let h = 2166136261; for (const c of s) { h ^= c.codePointAt(0); h = Math.imul(h, 16777619) >>> 0; } return h; }
function rng(seed){ let a = seed >>> 0; return () => { a = (a + 0x6D2B79F5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }

// 각 노드에서 끝점까지 최소 몇 걸음인지 미리 계산
const DIST = {};
(function(){
  const keys = Object.keys(N);
  for (const k of keys) DIST[k] = N[k].t ? 0 : Infinity;
  let changed = true;
  while (changed) {
    changed = false;
    for (const k of keys) for (const [to] of N[k].e || []) {
      if (N[to] && DIST[to] + 1 < DIST[k]) { DIST[k] = DIST[to] + 1; changed = true; }
    }
  }
})();

// 별칭 목록 (긴 것부터 찾음)
const ALIASES = [];
for (const [k, v] of Object.entries(N)) {
  for (const a of [k, ...(v.a || [])]) ALIASES.push([norm(a), k, a]);
}
ALIASES.sort((x, y) => y[0].length - x[0].length);

// 입력 속 별칭 찾기. 한 글자 별칭(폰, 밥, 배 등)은 입력 전체가 그 단어일 때만.
function findStart(q){
  const nq = norm(q);
  for (const [na, key, raw] of ALIASES) {
    if (!na) continue;
    if (na.length < 2 ? nq === na : nq.includes(na)) return {key, raw};
  }
  return null;
}

function pickOf(arr, r){ return arr[Math.floor(r() * arr.length) % arr.length]; }

// 연상 경로 만들기: 같은 입력 + 같은 variant 면 항상 같은 결과
function walk(q, variant = 0, avoidPick = null){
  const r = rng(hashStr(norm(q)) + variant * 7919);
  const steps = [[q, "오늘의 재료"]];
  const hit = findStart(q);
  let cur;
  if (hit) {
    cur = hit.key;
    if (norm(cur) !== norm(q)) steps.push([cur, norm(hit.raw) === norm(cur) ? "여기서 출발" : `${hit.raw} 하면 ${cur}`]);
  } else {
    const [b, why] = BRIDGES[Math.floor(r() * BRIDGES.length)];
    cur = b; steps.push([b, why]);
  }
  const seen = new Set([cur]);
  const hops = 3 + Math.floor(r() * 3);       // 출발 후 3~5걸음
  for (let h = 0; h < 8; h++) {
    const left = hops - h;
    const edges = (N[cur].e || []).filter(([to]) => N[to] && !seen.has(to));
    if (!edges.length) break;
    let ok = edges.filter(([to]) => left > 1 ? DIST[to] <= left - 1 : N[to].t);
    if (left > 1) {   // 아직 갈 길이 남았으면 막다른 단어는 피함
      const onward = ok.filter(([to]) => (N[to].e || []).some(([nx]) => N[nx] && !seen.has(nx) && nx !== to));
      if (onward.length) ok = onward;
    }
    if (avoidPick && left <= 1) ok = ok.filter(([to]) => !(N[to].t[1].length === 1 && norm(N[to].t[1][0]) === norm(avoidPick)));
    if (!ok.length) ok = edges.slice().sort((x, y) => DIST[x[0]] - DIST[y[0]]).slice(0, 1);
    const [to, why] = pickOf(ok, r);
    steps.push([to, why]); seen.add(to); cur = to;
    if (N[cur].t && left <= 1) break;
  }
  // 끝점이 아니면 가장 가까운 끝점까지 마저 걸어감
  for (let guard = 0; !N[cur].t && guard < 6; guard++) {
    const next = (N[cur].e || []).filter(([to]) => N[to]).sort((x, y) => DIST[x[0]] - DIST[y[0]])[0];
    if (!next) break;
    steps.push(next); cur = next[0];
  }
  const t = N[cur].t || ["관련주 미상", []];
  let picks = t[1].filter((p) => !avoidPick || norm(p) !== norm(avoidPick));
  if (!picks.length) picks = t[1];
  const pick = picks.length ? pickOf(picks, r) : null;
  const n = steps.length - 1;
  const fill = (s) => s.replace(/\{start\}/g, q).replace(/\{sector\}/g, t[0]).replace(/\{pick\}/g, pick || t[0]).replace(/\{n\}/g, n);
  return {
    steps, sector: t[0], pick, origin: null,
    leap: 60 + Math.floor(r() * 40),
    comment: fill(pickOf(COMMENTS, r)),
    matched: hit ? hit.raw : null,
  };
}

